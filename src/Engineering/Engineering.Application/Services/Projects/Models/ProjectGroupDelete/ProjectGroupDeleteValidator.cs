
namespace Engineering.Application.Services.Projects.Models.ProjectGroupDelete;

public class ProjectGroupDeleteValidator : AbstractValidator<ProjectGroupDeleteRequest>
{
    public ProjectGroupDeleteValidator()
    {
        RuleFor(c => c.Ids).NotEmpty().WithError(GlobalErrors.IdsIsEmpty).NotNull().WithError(GlobalErrors.IdsIsNull);
        RuleForEach(c => c.Ids).GreaterThan(0).WithError(GlobalErrors.IdsLessThanOrEqualZero);
    }
}
