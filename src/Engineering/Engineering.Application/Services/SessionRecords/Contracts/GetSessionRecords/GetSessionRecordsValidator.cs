namespace Engineering.Application.Services.SessionRecords.Contracts.GetSessionRecords;

public class GetSessionRecordsValidator : AbstractValidator<GetSessionRecordsRequest>
{
    public GetSessionRecordsValidator()
    {
        RuleFor(c => c.PageIndex)
            .PageIndexZero(GlobalCmts.PageIndex);
        RuleFor(c => c.PageSize)
            .PageSizeZero(GlobalCmts.PageSize);
        When(v => v.PageSize > 0, () =>
        {
            RuleFor(c => c.PageIndex)
                .PageIndexOne(GlobalCmts.PageIndex);
        });
    }
}
